export function splitInputProps(props: Record<string, unknown>) {
    const inputProps: InputProps = {};
    const rootProps: Record<string, unknown> = {};

    for (const [name, value] of Object.entries(props))
        (inputPropNames.has(name) || name.startsWith('aria-') ? inputProps : rootProps)[name] =
            value;
    return { inputProps, rootProps };
}
